from datetime import datetime
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class SyncOperationItem(BaseModel):
    operation_id: str = Field(..., description="Unique operation UUID generated by Flutter SyncQueue")
    entity_type: str = Field(..., description="Entity type: assessment_result, lesson, saved_material, feedback, lesson_delivery, worksheet_generation")
    entity_id: str = Field(..., description="Local client ID or remote UUID of the entity")
    operation: str = Field(..., description="CREATE, UPDATE, or DELETE")
    payload: Dict[str, Any] = Field(default_factory=dict, description="Entity attributes payload")
    client_updated_at: Optional[str] = None


class SyncUploadRequest(BaseModel):
    device_id: str
    teacher_id: Optional[str] = None
    app_version: Optional[str] = "1.0.0"
    android_version: Optional[str] = None
    operations: List[SyncOperationItem] = []


class OperationSyncResult(BaseModel):
    operation_id: str
    entity_type: str
    entity_id: str
    status: str  # SUCCESS, FAILED, CONFLICT, DUPLICATE_IGNORED
    remote_id: Optional[str] = None
    message: Optional[str] = None
    error: Optional[str] = None
    # Optional per-operation server data (e.g. worksheet generation job info).
    data: Optional[Dict[str, Any]] = None


class SyncUploadResponse(BaseModel):
    device_id: str
    total_operations: int
    successful_count: int
    failed_count: int
    results: List[OperationSyncResult] = []
    synced_at: datetime


class SyncCheckRequest(BaseModel):
    device_id: str
    app_version: str = "1.0.0"
    installed_packs: Dict[str, str] = {}  # e.g., {"ho": "1.0.0", "santali": "1.0.0"}
    last_sync_timestamp: Optional[datetime] = None


class SyncCheckResponse(BaseModel):
    device_id: str
    server_time: datetime
    updates_available: bool
    content_version: int
    language_pack_updates: List[str] = []  # Languages that have newer packs
    pending_server_updates_count: int = 0


class SyncManifestResponse(BaseModel):
    server_time: datetime
    content_version: int
    curriculum_version: str
    language_packs: List[Dict[str, Any]] = []
    models: List[Dict[str, Any]] = []


class SyncUpdatesResponse(BaseModel):
    server_time: datetime
    since: Optional[datetime] = None
    lessons: List[Dict[str, Any]] = []
    assessments: List[Dict[str, Any]] = []
    worksheets: List[Dict[str, Any]] = []
    verified_phrases: List[Dict[str, Any]] = []
